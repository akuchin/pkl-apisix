#!/usr/bin/env python3
"""
Generate Pkl modules from an APISIX schema snapshot (see tools/fetch-schema.sh).

Usage:
  python3 tools/generate.py schema/apisix-<version>.json

Writes:
  src/Apisix.pkl            core resources (Route, Service, Upstream, ...)
  src/Common.pkl            object types shared by several modules (plugin `_meta`, ...)
  src/Plugins.pkl           Plugins / ConsumerPlugins / StreamPlugins / PluginMetadata
  src/plugins/<name>.pkl    one module per HTTP plugin
  src/stream/<name>.pkl     one module per stream plugin
  build/typeinfo.json       type map used by tools/docs_examples.py
  COVERAGE.md               what is and is not checked by Pkl

Mapping rules (JSON Schema → Pkl):
  object + properties        → open class; optional properties are `T?` and default to null,
                               so APISIX applies its own defaults (documented in doc comments)
  object + pattern/additionalProperties → Mapping<String, T>
  array                      → Listing<T>
  enum / const               → literal union
  oneOf/anyOf of types       → union type
  required/not/oneOf/anyOf/allOf/if/dependencies/min|maxProperties on an object
                             → compiled to a constraint on `typealias Valid<Class>`
  everything Pkl cannot express is listed in COVERAGE.md; APISIX still checks it at load time.
"""

